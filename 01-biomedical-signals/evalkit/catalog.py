"""Generate docs/question-catalog.md (reviewer-friendly table with answers, reasoning and sources)."""
from __future__ import annotations

import sys
from pathlib import Path

from evalkit.grader import fmt_answer
from evalkit.schema import load_questions


def build(path, out) -> None:
    lines = ["# Question catalog", "", "Generated by `python -m evalkit.catalog`. Do not edit by hand.", ""]
    for q in load_questions(path):
        lines += [f"## {q.id} - {q.topic}", "", f"**Question:** {q.question}", "", f"**Answer:** `{fmt_answer(q.answer)}`", "",
                  f"**Reasoning:** {q.rationale}", "", f"**Designed shortcut:** {q.shortcut_trap} (gives `{fmt_answer(q.naive_answer)}`)", "",
                  f"**Verification:** {q.verification}" + (f" (`verifiers.{q.verifier}`)" if q.verifier else "")]
        if q.sources:
            lines += ["", "**Sources:**"] + [f"- {s['title']} - {s['locator']}" + (f" <{s['url']}>" if s.get("url") else "") for s in q.sources]
        lines.append("")
    Path(out).write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else "questions/questions.jsonl", sys.argv[2] if len(sys.argv) > 2 else "docs/question-catalog.md")
